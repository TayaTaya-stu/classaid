-- Fresh Shared Wall database bootstrap.
-- Run only in a newly created, empty Supabase project.
BEGIN;

CREATE TABLE public.posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    name TEXT NULL,
    message TEXT NULL,
    likes BIGINT NULL DEFAULT 0,
    laugh INTEGER NULL DEFAULT 0,
    sad INTEGER NULL DEFAULT 0,
    love INTEGER NULL DEFAULT 0,
    wow INTEGER NULL DEFAULT 0,
    is_ai BOOLEAN NULL DEFAULT FALSE,
    dislikes INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE public.post_likes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES public.posts(id) ON DELETE RESTRICT,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT post_likes_post_user_unique UNIQUE (post_id, user_id)
);

CREATE TABLE public.settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

ALTER TABLE public.posts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.post_likes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.settings ENABLE ROW LEVEL SECURITY;

COMMIT;
