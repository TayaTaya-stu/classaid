const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('classroomOverlay', {
  getInitialState: () => ipcRenderer.invoke('overlay:get-initial-state'),
  detectLatest: (sessionId) => ipcRenderer.invoke('overlay:detect-latest', sessionId),
  start: (config) => ipcRenderer.invoke('overlay:start', config),
  stop: () => ipcRenderer.invoke('overlay:stop'),
  test: () => ipcRenderer.invoke('overlay:test'),
  openScreen: (screenUrl) => ipcRenderer.invoke('overlay:open-screen', screenUrl),
  openAdmin: () => ipcRenderer.invoke('overlay:open-admin'),
  controlSession: (action, sessionId) => ipcRenderer.invoke('overlay:control-session', action, sessionId),
  configureConnection: (input) => ipcRenderer.invoke('overlay:configure-connection', input),
  stopAudioCapture: () => ipcRenderer.invoke('overlay:stop-audio'),
  sendAudioSegments: (sessionId, segments) => ipcRenderer.invoke('overlay:send-audio-segments', sessionId, segments),
  onStopAudio: (callback) => ipcRenderer.on('overlay:stop-audio', () => callback()),
  showQr: (screenUrl, displayId) => ipcRenderer.invoke('overlay:show-qr', screenUrl, displayId),
  hideQr: () => ipcRenderer.invoke('overlay:hide-qr'),
  onDisplays: (callback) => ipcRenderer.on('overlay:displays', (_event,value)=>callback(value)),
  onStatus: (callback) => ipcRenderer.on('overlay:status', (_event, value) => callback(value)),
  onPosts: (callback) => ipcRenderer.on('overlay:posts', (_event, value) => callback(value)),
  onEvents: (callback) => ipcRenderer.on('overlay:events', (_event, value) => callback(value)),
  onClear: (callback) => ipcRenderer.on('overlay:clear', () => callback()),
  onSetScreenUrl: (callback) => ipcRenderer.on('overlay:set-screen-url', (_event, value) => callback(value)),
  notifyRendered: (payload) => ipcRenderer.send('overlay:rendered', payload),
})
